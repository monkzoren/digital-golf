// The launch library: built-in courses beyond the tutorial pair and the Toy
// Box. Every hole here is LONG — two to five stages of hazards between the
// tee and the cup — and is designed around a HIDDEN hole-in-one: a line that
// exists, that a human can hit, but that is never the obvious one. Every
// hole is verified by `npm run check-courses` (spacetimedb/scripts), which
// plays it with the real physics: the ace is there and narrow, a decent
// player scores about par, the ball travels far enough for the par, and
// nothing rolls for ever.
//
// Reading a hole: x right, y DOWN, floors are rects (their boundary is a
// rail, WALL_H tall, that a lofted ball can fly over), blocks are polygons,
// zones are surfaces. Ramps (slope zones) are wedges: arrows point
// downhill, the far edge is a launch — a ball rolling off the top keeps
// climbing — so they are always entered from their low edge. A cannon loads the ball
// that rolls in; the next shot is the player's, lofted.
import {
  type Block, type Course, type Hole, R, polyRect,
  bumper, post, windmill, slider, pendulum, laser, rubber,
  sand, ice, water, slope, boost, jump, tele, conveyor, spinner, fan, trampoline, magnet, cannon,
} from './courses';

/** A triangle / any polygon block from flat points. */
const tri = (...pts: number[]): Block => ({ pts });
/** A low (jumpable) wall block. */
const low = (x: number, y: number, w: number, h: number, height = 1.2): Block => ({ ...polyRect(x, y, w, h), h: height });
/** A 45° mirror filling the top-right corner of a lane that ends at x=right, y=0..size. */
const mirrorTR = (right: number, size: number): Block => tri(right - size, 0, right, 0, right, size);

