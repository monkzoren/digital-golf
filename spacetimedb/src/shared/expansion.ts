// The expansion set: six more built-in courses. Every hole here is a FORK —
// there are always at least two real ways from the tee to the cup (through
// the tunnel or over the platform, up the ramp or round the lawn, the cannon
// or the causeway, the bank or the lane), and the hidden ace usually hides
// on the one nobody takes first. Verified like the launch library by
// `npm run check-courses`: an ace exists and is narrow, greedy play
// finishes near par, a decent player averages about par, nothing rolls for
// ever.
//
// Reading a hole: x right, y DOWN. `R(..., z)` is a raised platform whose
// edges are cliff faces (a ball on top rolls off, a ball below bounces off
// unless a ramp — `slopeTo` — meets it); `tunnel` bores a passage through a
// platform at ground level; `open` rects have NO rails (roll off and you
// are reset once the ball stops on the lawn). Ramps are wedges entered from
// their low edge; their `angle` points downhill.
